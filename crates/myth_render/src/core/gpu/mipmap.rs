use std::borrow::Cow;
use std::sync::Arc;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use rustc_hash::FxHashMap;

use super::PhysicalImageId;

/// Exact identity of one physical texture-content generation.
///
/// Asset handles and CPU-side versions deliberately stay outside this key:
/// they identify logical sources, while these two monotonically generated IDs
/// identify the concrete WGPU allocation and the base-level content currently
/// stored in it.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) struct PhysicalImageGenerationKey {
    pub(crate) physical: PhysicalImageId,
    pub(crate) allocation: u64,
    pub(crate) generation: u64,
}

/// A persistent texture whose mip chain must be generated by the RDG.
///
/// The request owns a cheap clone of the WGPU texture handle and an atomic
/// submission token shared with the owning `GpuImage`. GraphStorage owns each
/// frame's attempts; pass nodes carry only a Copy batch ID.
pub(crate) struct MipmapRequest {
    pub physical_id: PhysicalImageId,
    pub texture: wgpu::Texture,
    pub texture_id: u64,
    pub generation_id: u64,
    pub format: wgpu::TextureFormat,
    submitted_generation: Arc<AtomicU64>,
}

impl MipmapRequest {
    #[must_use]
    pub(crate) fn new(
        physical_id: PhysicalImageId,
        texture: wgpu::Texture,
        texture_id: u64,
        generation_id: u64,
        format: wgpu::TextureFormat,
        submitted_generation: Arc<AtomicU64>,
    ) -> Self {
        Self {
            physical_id,
            texture,
            texture_id,
            generation_id,
            format,
            submitted_generation,
        }
    }

    #[inline]
    #[must_use]
    pub(crate) const fn key(&self) -> PhysicalImageGenerationKey {
        PhysicalImageGenerationKey {
            physical: self.physical_id,
            allocation: self.texture_id,
            generation: self.generation_id,
        }
    }

    #[inline]
    pub(crate) fn mark_submitted(&self) {
        self.submitted_generation
            .fetch_max(self.generation_id, Ordering::Release);
    }

    #[cfg(test)]
    #[must_use]
    pub(crate) fn shares_submission_token(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.submitted_generation, &other.submitted_generation)
    }
}

/// Copy handle stored by an RDG node instead of borrowing Drop-bearing WGPU
/// request owners from another subsystem.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) struct MipmapBatchId(u32);

impl MipmapBatchId {
    #[inline]
    #[must_use]
    pub(crate) fn from_index(index: usize) -> Self {
        Self(u32::try_from(index).expect("mipmap batch index exceeds u32"))
    }

    #[inline]
    #[must_use]
    pub(crate) const fn index(self) -> usize {
        self.0 as usize
    }
}

/// GraphStorage-owned metadata for one staged request batch.
pub(crate) struct MipmapRequestBatch {
    requests: Vec<MipmapRequest>,
    encoded: AtomicBool,
}

impl MipmapRequestBatch {
    #[must_use]
    pub(crate) fn new(requests: Vec<MipmapRequest>) -> Self {
        Self {
            requests,
            encoded: AtomicBool::new(false),
        }
    }

    #[inline]
    pub(crate) fn mark_encoded(&self) {
        self.encoded.store(true, Ordering::Release);
    }

    #[inline]
    #[must_use]
    pub(crate) fn was_encoded(&self) -> bool {
        self.encoded.load(Ordering::Acquire)
    }

    #[inline]
    #[must_use]
    pub(crate) fn requests(&self) -> &[MipmapRequest] {
        &self.requests
    }

    pub(crate) fn publish_submitted(&self) {
        for request in &self.requests {
            request.mark_submitted();
        }
    }
}

/// Narrow request lookup capability shared by prepare and execute contexts.
#[derive(Clone, Copy)]
pub(crate) struct MipmapRequestResolver<'a> {
    batches: &'a [Option<MipmapRequestBatch>],
}

impl<'a> MipmapRequestResolver<'a> {
    #[must_use]
    pub(crate) const fn new(batches: &'a [Option<MipmapRequestBatch>]) -> Self {
        Self { batches }
    }

    fn batch(self, batch: MipmapBatchId) -> &'a MipmapRequestBatch {
        self.batches[batch.index()]
            .as_ref()
            .expect("mipmap request batch released before graph execution")
    }

    #[must_use]
    pub(crate) fn requests(self, batch: MipmapBatchId) -> &'a [MipmapRequest] {
        self.batch(batch).requests()
    }

    pub(crate) fn mark_encoded(self, batch: MipmapBatchId) {
        self.batch(batch).mark_encoded();
    }
}

struct MipmapStaticResources {
    layout: wgpu::BindGroupLayout,
    sampler: wgpu::Sampler,
    shader: wgpu::ShaderModule,
}

pub struct MipmapGenerator {
    static_resources: Option<MipmapStaticResources>,
    pipelines: FxHashMap<wgpu::TextureFormat, wgpu::RenderPipeline>,
}

impl MipmapGenerator {
    /// Creates a completely CPU-only generator. Shader, layout, sampler, and
    /// format pipelines are initialized by the first live prepare request.
    #[must_use]
    pub fn new(_device: &wgpu::Device) -> Self {
        Self {
            static_resources: None,
            pipelines: FxHashMap::default(),
        }
    }

    fn ensure_static_resources(&mut self, device: &wgpu::Device) {
        if self.static_resources.is_some() {
            return;
        }

        let shader = device.create_shader_module(wgpu::ShaderModuleDescriptor {
            label: Some("Mipmap Blit Shader"),
            source: wgpu::ShaderSource::Wgsl(Cow::Borrowed(include_str!(
                "../../pipeline/shaders/entry/utility/blit.wgsl"
            ))),
        });

        let layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("Mipmap Layout"),
            entries: &[
                wgpu::BindGroupLayoutEntry {
                    binding: 0,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Texture {
                        sample_type: wgpu::TextureSampleType::Float { filterable: true },
                        view_dimension: wgpu::TextureViewDimension::D2,
                        multisampled: false,
                    },
                    count: None,
                },
                wgpu::BindGroupLayoutEntry {
                    binding: 1,
                    visibility: wgpu::ShaderStages::FRAGMENT,
                    ty: wgpu::BindingType::Sampler(wgpu::SamplerBindingType::Filtering),
                    count: None,
                },
            ],
        });

        let sampler = device.create_sampler(&wgpu::SamplerDescriptor {
            label: Some("Mipmap Sampler"),
            mag_filter: wgpu::FilterMode::Linear,
            min_filter: wgpu::FilterMode::Linear,
            mipmap_filter: wgpu::MipmapFilterMode::Linear,
            address_mode_u: wgpu::AddressMode::ClampToEdge,
            address_mode_v: wgpu::AddressMode::ClampToEdge,
            ..Default::default()
        });

        self.static_resources = Some(MipmapStaticResources {
            layout,
            sampler,
            shader,
        });
    }

    fn create_pipeline(
        &self,
        device: &wgpu::Device,
        format: wgpu::TextureFormat,
    ) -> wgpu::RenderPipeline {
        let resources = self
            .static_resources
            .as_ref()
            .expect("mipmap static resources missing after prepare");
        device.create_render_pipeline(&wgpu::RenderPipelineDescriptor {
            label: Some(&format!("Mipmap Pipeline {format:?}")),
            layout: Some(
                &device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
                    label: Some("Mipmap Pipeline Layout"),
                    bind_group_layouts: &[Some(&resources.layout)],
                    immediate_size: 0,
                }),
            ),
            vertex: wgpu::VertexState {
                module: &resources.shader,
                entry_point: Some("vs_main"),
                buffers: &[],
                compilation_options: wgpu::PipelineCompilationOptions::default(),
            },
            fragment: Some(wgpu::FragmentState {
                module: &resources.shader,
                entry_point: Some("fs_main"),
                targets: &[Some(wgpu::ColorTargetState {
                    format,
                    blend: None,
                    write_mask: wgpu::ColorWrites::ALL,
                })],
                compilation_options: wgpu::PipelineCompilationOptions::default(),
            }),
            primitive: wgpu::PrimitiveState {
                topology: wgpu::PrimitiveTopology::TriangleList,
                ..Default::default()
            },
            depth_stencil: None,
            multisample: wgpu::MultisampleState::default(),
            multiview_mask: None,
            cache: None,
        })
    }

    /// Pre-warm the pipeline cache for a given texture format.
    /// Call this during the prepare phase (when `&mut self` is available).
    pub fn ensure_pipeline(&mut self, device: &wgpu::Device, format: wgpu::TextureFormat) {
        if !self.pipelines.contains_key(&format) {
            self.ensure_static_resources(device);
            let pipeline = self.create_pipeline(device, format);
            self.pipelines.insert(format, pipeline);
        }
    }

    /// Generate mipmaps for the given texture.
    ///
    /// **Important**: The pipeline for the texture's format must be pre-warmed
    /// via [`ensure_pipeline`] during the prepare phase.
    pub fn generate(
        &self,
        device: &wgpu::Device,
        encoder: &mut wgpu::CommandEncoder,
        texture: &wgpu::Texture,
    ) {
        let mip_count = texture.mip_level_count();
        if mip_count < 2 {
            return;
        }

        let format = texture.format();
        let pipeline = self
            .pipelines
            .get(&format)
            .unwrap_or_else(|| panic!("mipmap pipeline for {format:?} was not prepared"))
            .clone();
        let resources = self
            .static_resources
            .as_ref()
            .expect("mipmap static resources missing after prepare");
        let layer_count = texture.depth_or_array_layers();

        for layer in 0..layer_count {
            for i in 0..mip_count - 1 {
                let src_view = texture.create_view(&wgpu::TextureViewDescriptor {
                    label: Some("Mipmap Src"),
                    format: None,
                    dimension: Some(wgpu::TextureViewDimension::D2),
                    aspect: wgpu::TextureAspect::All,
                    base_mip_level: i,
                    mip_level_count: Some(1),
                    base_array_layer: layer,
                    array_layer_count: Some(1),
                    usage: Some(wgpu::TextureUsages::TEXTURE_BINDING),
                });

                let dst_view = texture.create_view(&wgpu::TextureViewDescriptor {
                    label: Some("Mipmap Dst"),
                    format: None,
                    dimension: Some(wgpu::TextureViewDimension::D2),
                    aspect: wgpu::TextureAspect::All,
                    base_mip_level: i + 1,
                    mip_level_count: Some(1),
                    base_array_layer: layer,
                    array_layer_count: Some(1),
                    usage: Some(wgpu::TextureUsages::RENDER_ATTACHMENT),
                });

                let bind_group = device.create_bind_group(&wgpu::BindGroupDescriptor {
                    label: Some("Mipmap BG"),
                    layout: &resources.layout,
                    entries: &[
                        wgpu::BindGroupEntry {
                            binding: 0,
                            resource: wgpu::BindingResource::TextureView(&src_view),
                        },
                        wgpu::BindGroupEntry {
                            binding: 1,
                            resource: wgpu::BindingResource::Sampler(&resources.sampler),
                        },
                    ],
                });

                let mut rpass = encoder.begin_render_pass(&wgpu::RenderPassDescriptor {
                    label: Some("Mipmap Pass"),
                    color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                        view: &dst_view,
                        resolve_target: None,
                        ops: wgpu::Operations {
                            load: wgpu::LoadOp::Clear(wgpu::Color::BLACK),
                            store: wgpu::StoreOp::Store,
                        },
                        depth_slice: None,
                    })],
                    depth_stencil_attachment: None,
                    timestamp_writes: None,
                    occlusion_query_set: None,
                    multiview_mask: None,
                });
                rpass.set_pipeline(&pipeline);
                rpass.set_bind_group(0, &bind_group, &[]);
                rpass.draw(0..3, 0..1);
            }
        }
    }

    #[cfg(test)]
    #[must_use]
    pub(crate) fn is_initialized(&self) -> bool {
        self.static_resources.is_some()
    }
}
